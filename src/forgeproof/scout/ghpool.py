"""The GitHub pool's admission gate for ``forgeproof learn --github`` (design §12.5; build step
7 slice 4; DECISIONS-7-github G4, G5, G7; lifts L2's "for now" for the GitHub pool ONLY).

A file is admitted only if every check holds, in this order. Each failure is its own BLIND
reason, and nothing is written:
1. the spec is ``org/repo@<40 hex>``, and a signed line verifies for exactly that pin:
   BLIND(unsigned);
2. the whole-cache pin check passes: BLIND(pin-mismatch);
3. the repo licence is on the allowlist, and the signed ``licence_blob`` is the blob of a
   top-level licence file at the pin: BLIND(licence);
4. the per-file pin check passes at the read (its bytes are needed by 5 and 6):
   BLIND(pin-mismatch);
5. per-file inclusion (extension, source tree, not generated): BLIND(not-included);
6. the file carries no licence marker of its own that is off the allowlist:
   BLIND(licence-file).

The admitted file becomes an ``item`` that learn's engines take exactly as they take a corpus
item, so the battery, the survival gate and chaos's rules (KD-12 j: BLIND unless a probed library
file, and BLIND then as a library copy) are the same code path for both pools (G6).
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath

from . import fetchproxy, ghcache, ratify

POOL = "github"
# KD-13 (f): the signed list and its signer file are found through config.scout_list_dir()
# (FORGEPROOF_SCOUT_LIST_DIR, default <checkout>/scout), never through this file's position, so an
# installed ForgeProof can be pointed at them. Both are tracked and public-safe (G8).
LIST_NAME = "trusted_repos.jsonl"
SIGNERS_NAME = "allowed_signers"
# Test-only overrides, None in real use: a test may point admit() at its own files.
LIST_FILE: Path | None = None
SIGNERS_FILE: Path | None = None


def list_files() -> tuple[Path, Path]:
    """(trusted_repos.jsonl, allowed_signers). Raises config.NotConfigured naming the key when no
    folder can be found (KD-13 f)."""
    if LIST_FILE is not None and SIGNERS_FILE is not None:
        return LIST_FILE, SIGNERS_FILE
    from .. import config
    d = config.scout_list_dir()
    return (LIST_FILE or d / LIST_NAME), (SIGNERS_FILE or d / SIGNERS_NAME)

# G4 (the maintainer 2026-11-14): a CLOSED set. Copyleft and anything unknown stay out (§12.8 Q5).
# KD-13 (d) (the maintainer 2026-11-15): PSF-2.0 added; it is a component of the Python-2.0 stack.
ALLOWLIST = frozenset({"Apache-2.0", "MIT", "BSD-2-Clause", "BSD-3-Clause", "ISC", "Python-2.0", "PSF-2.0"})
LICENCE_FILES = ("LICENSE", "LICENSE.txt", "LICENSE.md", "LICENCE", "COPYING")
EXTENSIONS = {".py": "python", ".r": "r", ".R": "r", ".cpp": "cpp", ".go": "go", ".rs": "rust", ".js": "javascript"}
NOT_SOURCE = frozenset({"test", "tests", "testing", "example", "examples", "doc", "docs", "Doc",
                        "demo", "demos", "benchmarks", "bench"})
GENERATED = re.compile(rb"(?i)(do not edit|@generated|autogenerated|auto-generated|generated by|"
                       rb"this file was generated|code generated)")
_SPDX_LINE = re.compile(r"SPDX-License-Identifier:\s*(.+?)\s*(?:\*/|-->)?\s*$", re.M)   # review F1: re.M
_OTHER_LICENCE = re.compile(
    r"(?i)(GNU (Lesser |Library |Affero )?General Public|\b[AL]?GPL|Mozilla Public|\bMPL\b|Eclipse Public|"
    r"\bEPL\b|\bEUPL\b|\bCDDL\b|\bOSL\b|Open Software License|Creative Commons|\bCC-BY|\bSSPL\b|"
    r"Server Side Public|Business Source|\bBUSL\b|Elastic License|LicenseRef-|proprietary|"
    r"all rights reserved\.?\s*(no|not)|Commons Clause)")
_SPEC = re.compile(r"([^/@\s]+)/([^/@\s]+)@([0-9a-f]{40})")   # used with fullmatch (review F6)
_TOKEN = re.compile(r"\(|\)|[A-Za-z0-9.+-]+")


class NotAdmitted(Exception):
    """The file is not admitted; str(e) is the BLIND reason."""


def spdx_allowed(expr: str) -> bool:
    """An SPDX expression over the allowlist: OR passes if any branch passes, AND needs every
    branch, parentheses group. WITH, '+' or anything unparsable is refused (fail closed)."""
    toks = _TOKEN.findall(expr or "")
    if "".join(toks) != re.sub(r"\s+", "", expr or "") or not toks:
        return False
    pos = 0

    def atom():
        nonlocal pos
        if pos >= len(toks):
            raise ValueError("end")
        t = toks[pos]
        pos += 1
        if t == "(":
            v = disj()
            if pos >= len(toks) or toks[pos] != ")":
                raise ValueError(")")
            pos += 1
            return v
        if t in ("AND", "OR", "WITH", ")") or t.endswith("+"):
            raise ValueError(t)
        return t in ALLOWLIST

    def conj():
        nonlocal pos
        v = atom()
        while pos < len(toks) and toks[pos] == "AND":
            pos += 1
            v = atom() and v
        return v

    def disj():
        nonlocal pos
        v = conj()
        while pos < len(toks) and toks[pos] == "OR":
            pos += 1
            v = conj() or v
        return v

    try:
        v = disj()
    except ValueError:
        return False
    return v if pos == len(toks) else False


def file_licence(text: str) -> str:
    """'' when the file carries no licence marker of its own (it inherits the repo's), else the
    reason it is not admitted. Only the first 40 lines are read."""
    head = "\n".join(text.splitlines()[:40])
    for m in _SPDX_LINE.finditer(head):
        if not spdx_allowed(m.group(1)):
            return f"licence-file: SPDX {m.group(1)!r} is not on the allowlist"
    m = _OTHER_LICENCE.search(head)       # ALWAYS, SPDX line or not (G4 c; review F1)
    if m:
        return f"licence-file: header names {m.group(0)!r}"
    return ""


def included(path: str, data: bytes) -> str:
    """'' when §12.5's per-file inclusion holds, else the reason."""
    p = PurePosixPath(path)
    if p.suffix not in EXTENSIONS:
        return f"not-included: extension {p.suffix!r}"
    hit = [d for d in p.parts[:-1] if d in NOT_SOURCE or d.lower() in NOT_SOURCE]
    if hit:
        return f"not-included: under {hit[0]}/ (test, example or docs)"
    if p.name.startswith("test_") or p.name.endswith("_test" + p.suffix):
        return "not-included: a test file"
    if GENERATED.search(data[:2048]):
        return "not-included: a generated-code marker in the first 2 KB"
    return ""


THRESHOLDS = {"first_commit_age_years": (">=", 3), "last_commit_age_days": ("<=", 180),
              "contributors": (">=", 10), "closed_issues": (">=", 50), "dependents": (">=", 100)}


def trust_score(signals: dict) -> dict:
    """§12.5's signals as met/known (G7): an unknown signal is shown as unknown, never as met.
    Each signal is {"value": number or null, "source": text}."""
    met, known, unknown = 0, 0, []
    for k, (op, t) in THRESHOLDS.items():
        v = (signals.get(k) or {}).get("value") if isinstance(signals.get(k), dict) else None
        if not isinstance(v, (int, float)) or isinstance(v, bool):
            unknown.append(k)
            continue
        known += 1
        met += (v >= t) if op == ">=" else (v <= t)
    return {"met": met, "known": known, "unknown": unknown, "of": len(THRESHOLDS)}


@dataclass
class Admitted:
    org: str
    repo: str
    commit: str
    path: str
    lang: str
    data: bytes
    verdict: ratify.Verdict
    trust: dict = field(default_factory=dict)

    @property
    def source(self) -> str:
        return f"{self.org}/{self.repo}"

    def item(self) -> dict:
        return {"item_id": self.source, "body": self.data.decode("utf-8"), "file": self.path,
                "lang": self.lang}


TRUST_PIN_KEY = "FORGEPROOF_RATIFY_PIN"   # untracked config: "operator=<16-hex key id>" (review open question)


def trust_pin(raw: str | None) -> tuple[str, str] | None:
    m = re.fullmatch(r"([a-z][a-z0-9-]{0,31})=([0-9a-f]{16})", (raw or "").strip())
    return (m.group(1), m.group(2)) if m else None


def admit(spec: str, path: str, *, list_file: Path | None = None, signers_file: Path | None = None,
          cache_root: Path | None = None, host_sets_file: Path | None = None,
          trust_pin_value: str | None = None) -> Admitted:
    m = _SPEC.fullmatch(spec or "")
    if not m:
        raise NotAdmitted(f"unsigned: --github must be org/repo@<40-hex commit>: {spec!r}")
    org, repo, commit = m.groups()
    try:
        sets, _ = fetchproxy.load_host_sets(host_sets_file or fetchproxy.HOST_SETS_FILE)
    except (OSError, ValueError) as e:
        raise NotAdmitted(f"unsigned: host sets unreadable: {e}") from None
    if list_file is None or signers_file is None:
        from .. import config
        try:
            found_list, found_signers = list_files()
        except config.NotConfigured as e:   # loud, names the key; nothing is read or written
            raise NotAdmitted(f"unsigned: no signed list: {e}") from None
        list_file = list_file or found_list
        signers_file = signers_file or found_signers
    v = ratify.ratified(list_file, signers_file, org, repo, commit, sets)
    if not v.ok:
        raise NotAdmitted(f"unsigned: {org}/{repo}@{commit}: {v.reason}")
    # The signer file is in the repo, so whoever can commit could swap the key under "operator". The
    # required signer's key id is therefore ALSO pinned in the host's untracked config.
    from .. import config
    pin = trust_pin(trust_pin_value if trust_pin_value is not None else config.configured(TRUST_PIN_KEY))
    if pin is None or pin[0] != ratify.REQUIRED_PRINCIPAL:
        raise NotAdmitted(f"unsigned: {TRUST_PIN_KEY} must be set to '{ratify.REQUIRED_PRINCIPAL}=<key id>' "
                          "in the host's config (the trust root is pinned outside the repo)")
    signed = dict(zip(v.principals, v.key_ids))
    if signed.get(pin[0]) != pin[1]:
        raise NotAdmitted(f"unsigned: {pin[0]}'s signature is by key {signed.get(pin[0])}, the host pins {pin[1]}")
    try:
        ghcache.check_cache(org, repo, commit, v, root=cache_root)
        store = (Path(cache_root) if cache_root is not None else ghcache.cache_root()) / ".objects" / org / f"{repo}.git"
        tree = ghcache.tree_files(store, commit)
    except ghcache.PinMismatch as e:
        raise NotAdmitted(f"pin-mismatch: {e}") from None
    spdx = v.fields["licence_spdx"]
    if not spdx_allowed(spdx):
        raise NotAdmitted(f"licence: {spdx!r} is not on the allowlist")
    present = [n for n in LICENCE_FILES if n in tree]
    if not present or any(tree[n][1] != v.fields["licence_blob"] for n in present):
        raise NotAdmitted(f"licence: the top-level licence file(s) {present} at {commit[:12]} are not all "
                          f"the signed blob {v.fields['licence_blob'][:12]} (review F5: every one must be)")
    try:
        data = ghcache.read_file(org, repo, commit, path, v, root=cache_root)
    except ghcache.PinMismatch as e:
        raise NotAdmitted(f"pin-mismatch: {e}") from None
    why = included(path, data)
    if why:
        raise NotAdmitted(why)
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        raise NotAdmitted("not-included: not UTF-8 text") from None
    why = file_licence(text)
    if why:
        raise NotAdmitted(why)
    return Admitted(org, repo, commit, path, EXTENSIONS[PurePosixPath(path).suffix], data, v,
                    trust_score(v.fields.get("trust_signals") or {}))
